def gerar_pergunta():
    operacao = random.choice(["+", "-", "×", "÷"])

    if operacao == "+":
        a, b = random.randint(10, 99), random.randint(1, 99)
        resposta = a + b
    elif operacao == "-":
        a = random.randint(20, 99)
        b = random.randint(1, a)
        resposta = a - b
    elif operacao == "×":
        a, b = random.randint(2, 12), random.randint(2, 10)
        resposta = a * b
    else:
        b = random.randint(2, 10)
        resposta = random.randint(2, 12)
        a = b * resposta

    # Criar quatro alternativas diferentes
    alternativas = {resposta}
    while len(alternativas) < 4:
        erro = resposta + random.choice(
            [-12, -8, -5, -3, -2, 2, 3, 5, 8, 12]
        )
        if erro >= 0 and erro != resposta:
            alternativas.add(erro)

    alternativas = list(alternativas)
    random.shuffle(alternativas)

    return {
        "texto": f"{a} {operacao} {b} = ?",
        "resposta": resposta,
        "alternativas": alternativas
    }



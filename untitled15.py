def criar_som():
    buffer = io.BytesIO()
    sample_rate = 22050
    duracao = 0.45

    with wave.open(buffer, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)

        samples = []
        for i in range(int(sample_rate * duracao)):
            t = i / sample_rate
            freq = 660 if t < 0.18 else 880
            envelope = min(1, t * 15) * max(
                0, 1 - t / duracao
            )
            valor = int(
                10000 * envelope *
                math.sin(2 * math.pi * freq * t)
            )
            samples.append(struct.pack("<h", valor))

        wav.writeframes(b"".join(samples))

    return base64.b64encode(buffer.getvalue()).decode()


def tocar_som():
    audio = criar_som()
    components.html(
        f"""
        <audio autoplay>
          <source src="data:audio/wav;base64,{audio}"
                  type="audio/wav">
        </audio>
        """,
        height=0
    )


